create table if not exists public.event_enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  event_type text not null,
  event_date date,
  guest_count integer,
  source text not null default 'website',
  created_at timestamptz not null default now()
);

alter table public.event_enquiries enable row level security;

grant insert on table public.event_enquiries to anon;
grant usage, select on sequence public.event_enquiries_id_seq to anon;

drop policy if exists "Allow public event enquiry inserts" on public.event_enquiries;
create policy "Allow public event enquiry inserts"
  on public.event_enquiries
  for insert
  to anon
  with check (true);
